/**
 * CareerNode represents a single career option in the career graph.
 * Nodes are connected by edges that represent transition paths.
 */
export interface CareerNode {
  /** Unique identifier for this career */
  id: EntityId;
  
  /** Human-readable name (e.g., "Software Engineer") */
  name: string;
  
  /** Detailed description of what this career entails */
  description: string;
  
  /** Industry or sector (e.g., "Technology", "Healthcare") */
  industry: string;
  
  /** Category of work (e.g., "Technical", "Creative", "Service") */
  category: CareerCategory;
  
  /** Required strengths for this career */
  requiredStrengths: StrengthRequirement[];
  
  /** Values that align with this career */
  alignedValues: ValueAlignment[];
  
  /** Lifestyle characteristics of this career */
  lifestyleProfile: LifestyleProfile;
  
  /** Entry requirements (education, experience, certifications) */
  entryRequirements: EntryRequirement[];
  
  /** Career trajectory information */
  trajectory: CareerTrajectory;
  
  /** Market data for this career */
  marketData: CareerMarketData;
  
  /** Metadata for reasoning */
  metadata: {
    /** When this career data was last updated */
    lastUpdated: BeliefTimestamp;
    
    /** Data source (BLS, industry reports, etc.) */
    dataSource: string;
    
    /** Confidence in this career data */
    dataConfidence: ConfidenceScore;
  };
}

