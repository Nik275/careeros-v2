/**
 * StudentBelief V3 - Enhanced with Reality Domains and Decision State
 *
 * V3 adds four new intelligence domains to the StudentBelief model:
 *   1. FamilyReality - Family context, obligations, expectations
 *   2. EconomicReality - Financial situation, constraints, resources
 *   3. EducationalReality - Academic background, achievements, opportunities
 *   4. DecisionState - Timeline, pressure, readiness, context
 *
 * These domains enable more nuanced career recommendations that account
 * for the student's complete reality - not just their psychology.
 */
export interface StudentBeliefV3 {
  /** Unique identifier for this belief snapshot */
  id: EntityId;

  /** Student identifier this belief belongs to */
  studentId: EntityId;

  /** Version number (V3 = 3) */
  version: 3;

  /** When this belief snapshot was created */
  timestamp: BeliefTimestamp;

  // ==========================================================================
  // PSYCHOLOGY LAYER (from V2)
  // ==========================================================================

  /** What drives this student's career decisions */
  motivations: Motivation[];

  /** What this student is good at */
  strengths: Strength[];

  /** What this student cares about */
  values: Value[];

  /** How this student thinks and behaves */
  personalityTraits: PersonalityTrait[];

  /** How this student wants to live */
  lifestylePreferences: LifestylePreference[];

  /** What limits this student's options */
  constraints: Constraint[];

  // ==========================================================================
  // REALITY LAYER (NEW in V3)
  // ==========================================================================

  /** Family reality - obligations, expectations, support, cultural factors */
  familyReality: FamilyReality;

  /** Economic reality - financial situation, constraints, resources */
  economicReality: EconomicReality;

  /** Educational reality - academic background, achievements, opportunities */
  educationalReality: EducationalReality;

  // ==========================================================================
  // DECISION CONTEXT LAYER (NEW in V3)
  // ==========================================================================

  /** Decision state - timeline, pressure, readiness, context */
  decisionState: DecisionStateType;

  // ==========================================================================
  // METADATA
  // ==========================================================================

  /** Overall confidence in the belief model */
  overallConfidence: ConfidenceScore;

  /** Whether this belief has been validated through follow-up or external data */
  isValidated: boolean;

  /** Previous version of this belief (for tracking evolution) */
  previousVersionId?: EntityId;

  /** Metadata for debugging and analytics */
  metadata: {
    /** How many assessment questions contributed to this belief */
    assessmentQuestionCount: number;

    /** How many inference steps were applied */
    inferenceStepCount: number;

    /** Which engines contributed to this belief */
    contributingEngines: string[];

    /** Time spent in assessment (milliseconds) */
    assessmentDuration: number;

    /** Migration info if upgraded from V2 */
    migratedFromV2?: {
      originalVersion: number;
      migratedAt: BeliefTimestamp;
      migrationReason: string;
    };
  };
}
