/**
 * CareerPath represents a sequence of career nodes and edges.
 * Paths are generated by the PathCascade engine and evaluated by other engines.
 */
export interface CareerPath {
  /** Unique identifier for this path */
  id: EntityId;
  
  /** Human-readable name for this path */
  name: string;
  
  /** Ordered sequence of career nodes in this path */
  nodes: CareerNode[];
  
  /** Edges connecting the nodes */
  edges: CareerEdge[];
  
  /** Total years for this path */
  totalYears: number;
  
  /** Student belief this path was generated for */
  studentBeliefId: EntityId;
  
  /** Scores from various evaluation engines */
  scores: PathScores;
  
  /** Whether this path has been validated by the student */
  isValidated: boolean;
  
  /** When this path was generated */
  generatedAt: BeliefTimestamp;
}

/**
 * Scores for a career path from various evaluation dimensions.
 */
export interface PathScores {
  /** How well this path matches student motivations (0.0 - 1.0) */
  motivationAlignment: ConfidenceScore;
  
  /** How well this path leverages student strengths (0.0 - 1.0) */
  strengthUtilization: ConfidenceScore;
  
  /** How well this path satisfies student values (0.0 - 1.0) */
  valueSatisfaction: ConfidenceScore;
  
  /** How feasible this path is given constraints (0.0 - 1.0) */
  feasibility: ConfidenceScore;
  
  /** Predicted regret score (lower is better) */
  predictedRegret: ConfidenceScore;
  
  /** Overall path quality score (composite) */
  overall: ConfidenceScore;
}

